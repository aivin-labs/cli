/**
 * Ngôn ngữ của máy: AIVIN_LANG → LANG / LC_ALL (trừ Windows: ở đó chỉ shell kiểu Unix như Git Bash đặt, không phải người dùng chọn) →
 * ngôn ngữ hệ điều hành (Intl); không có bản dịch → en.
 */
export function mascotLang(env = process.env, platform = process.platform) {
  const candidates = [env.AIVIN_LANG, ...(platform === 'win32' ? [] : [env.LC_ALL, env.LANG])];
  try { candidates.push(Intl.DateTimeFormat().resolvedOptions().locale); } catch { /* không có Intl */ }
  for (const c of candidates) {
    const code = String(c || '').toLowerCase().split(/[-_.]/)[0];
    if (STRINGS[code]) return code;
  }
  return 'en';
}

const fill = (text, vars = {}) => String(text).replace(/\{(\w+)\}/g, (_, k) => (vars[k] ?? `{${k}}`));

export function mascotText(lang, key, vars) {
  return fill((STRINGS[lang] || STRINGS.en)[key] ?? STRINGS.en[key] ?? key, vars);
}

export function mascotVerb(lang, verb) {
  return (VERBS[lang] || VERBS.en)[verb] ?? VERBS.en[MascotVerb.OTHER];
}

/** Toàn bộ chữ tĩnh của cửa sổ (gửi cho tiến trình hiển thị một lần lúc mở). */
export function windowStrings(lang) {
  return Object.fromEntries(Object.values(MascotText).map((k) => [k, mascotText(lang, k)]));
}
